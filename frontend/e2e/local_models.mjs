// End-to-end check of LOCAL speech and image models, with stand-in model servers (stub_local_models.py).
// Chromium gets a fake microphone that plays a tone followed by silence, so the real capture -> voice-activity
// detection -> upload path runs. Needs the backend started with the env shown in docs/LOCAL_MODELS.md.
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const BASE = process.env.BASE || "http://127.0.0.1:8767";
const STUB = process.env.STUB || "http://127.0.0.1:9911";
const MIC = process.env.MIC_WAV;
const SHOTS = path.join(path.dirname(fileURLToPath(import.meta.url)), "screenshots");
let failed = 0;
const check = (name, ok, detail = "") => { if (!ok) failed++; console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? "  (" + detail + ")" : ""}`); };
const stubLog = async () => (await fetch(STUB)).json();

const browser = await chromium.launch({ args: ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", `--use-file-for-fake-audio-capture=${MIC}`, "--autoplay-policy=no-user-gesture-required"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, permissions: ["microphone"] });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
try {
  await page.goto(`${BASE}/api/auth?token=${process.env.TOKEN || "dev-token"}&next=/`);
  await page.waitForSelector('[data-testid="screen-home"]', { timeout: 15000 });
  const shim = await page.evaluate(() => ({ rec: window.SpeechRecognition?.jarvisLocal === true, synth: window.speechSynthesis?.jarvisLocal === true }));
  check("UI switched to the local speech models", shim.rec && shim.synth, JSON.stringify(shim));

  await page.click('[data-testid="nav-voice"]');
  await page.waitForSelector('[data-testid="voice-stage"]');
  const chatReq = page.waitForRequest((r) => r.url().endsWith("/api/chat") && r.method() === "POST", { timeout: 30000 });
  await page.click('[role="switch"][aria-label="Wake word listening"]');
  const body = (await chatReq).postDataJSON();
  let log = await stubLog();
  const stt = log.find((l) => l.path.endsWith("/audio/transcriptions"));
  check("microphone audio was captured, segmented and sent to the local speech-to-text server", !!stt && stt.bytes > 2000 && stt.multipart, stt ? `${stt.bytes} bytes` : "no request");
  check("transcript drove a voice request (wake word detected and stripped)", body.source === "voice" && /^how is my computer performing/i.test(body.text), JSON.stringify(body.text));
  await page.waitForFunction(() => /System performance/.test(document.querySelector('[data-testid="voice-reply"]')?.textContent || ""), null, { timeout: 20000 });
  await page.waitForFunction(async (u) => (await (await fetch(u)).json()).some((l) => l.path.endsWith("/audio/speech")), STUB, { timeout: 15000 }).catch(() => {});
  log = await stubLog();
  const tts = log.filter((l) => l.path.endsWith("/audio/speech"));
  check("reply was synthesised by the local text-to-speech server", tts.length > 0 && /System performance/.test(tts[0].input), tts[0]?.input);
  await page.waitForFunction(() => document.querySelector('[data-testid="assistant-state"]')?.textContent?.toLowerCase().includes("speaking"), null, { timeout: 10000 }).then(() => check("synthesised audio actually played (assistant state: speaking)", true), () => check("synthesised audio actually played (assistant state: speaking)", false));
  await page.screenshot({ path: path.join(SHOTS, "11-local-voice.png") });
  await page.click('[role="switch"][aria-label="Wake word listening"]');
  await page.click('[data-testid="voice-stop"]').catch(() => {});

  await page.click('[data-testid="nav-conversations"]');
  await page.fill('[data-testid="conv-composer"] textarea, [data-testid="conv-composer"] input', "generate an image of a red fox in the snow");
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => { const i = document.querySelector('[data-testid="thread"] .md img'); return i && i.complete && i.naturalWidth > 0; }, null, { timeout: 30000 });
  log = await stubLog();
  const img = log.find((l) => l.path.endsWith("/txt2img"));
  check("image generated by the local image server and shown in the conversation", !!img && img.prompt === "a red fox in the snow", JSON.stringify(img?.prompt));
  await page.screenshot({ path: path.join(SHOTS, "12-local-image.png") });
  check("no page errors", errors.length === 0, errors.slice(0, 2).join(" | "));
} catch (e) {
  check("run completed without an exception", false, String(e).split("\n")[0]);
  await page.screenshot({ path: path.join(SHOTS, "failure-local.png") }).catch(() => {});
  console.log(JSON.stringify(await stubLog().catch(() => [])), errors.join(" | "));
}
await browser.close();
process.exit(failed ? 1 : 0);
